[CmdletBinding()]
param(
    [string]$Compiler = 'glslangValidator',
    [string]$Validator = 'spirv-val',
    [string]$WslDistribution,
    [switch]$Check
)
$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
$shaderDir = Join-Path $repo 'dotnet/src/Sed.Rendering.Vulkan/Shaders'
$outputDir = Join-Path $repo ('build/shader-compile-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $outputDir | Out-Null
$shaderNames = @('mesh.vert', 'mesh.frag', 'triangle.vert', 'triangle.frag')

function Invoke-ShaderTool([string]$Tool, [string[]]$ToolArguments) {
    if ($WslDistribution) { & wsl.exe -d $WslDistribution --exec $Tool @ToolArguments }
    else { & $Tool @ToolArguments }
    if ($LASTEXITCODE -ne 0) { throw "$Tool failed with exit code $LASTEXITCODE." }
}
function Tool-Path([string]$Path) {
    if (!$WslDistribution) { return $Path }
    $value = & wsl.exe -d $WslDistribution --exec wslpath -a $Path
    if ($LASTEXITCODE -ne 0) { throw "Cannot resolve shader path in WSL: $Path" }
    return ($value | Out-String).Trim()
}

$compilerVersion = (Invoke-ShaderTool $Compiler @('--version') | Out-String).Trim()
$validatorVersion = (Invoke-ShaderTool $Validator @('--version') | Out-String).Trim()
$rows = @()
foreach ($name in $shaderNames) {
    $source = Join-Path $shaderDir $name
    $compiled = Join-Path $outputDir ($name + '.spv')
    $sourceHash = (Get-FileHash -LiteralPath $source -Algorithm SHA256).Hash
    Invoke-ShaderTool $Compiler @('-V', '--target-env', 'vulkan1.0', (Tool-Path $source), '-o', (Tool-Path $compiled))
    Invoke-ShaderTool $Validator @('--target-env', 'vulkan1.0', (Tool-Path $compiled))
    if ((Get-FileHash -LiteralPath $source -Algorithm SHA256).Hash -ne $sourceHash) {
        throw "Shader changed during compilation: $name"
    }
    $rows += [ordered]@{
        source = $name
        sourceSha256 = $sourceHash
        binary = $name + '.spv'
        binarySha256 = (Get-FileHash -LiteralPath $compiled -Algorithm SHA256).Hash
    }
}
# No committed output changes until every shader compiles and validates.
foreach ($row in $rows) {
    if ((Get-FileHash -LiteralPath (Join-Path $shaderDir $row.source) -Algorithm SHA256).Hash -ne $row.sourceSha256) {
        throw "Shader changed before publication: $($row.source)"
    }
}
foreach ($row in $rows) {
    $destination = Join-Path $shaderDir $row.binary
    if ($Check) {
        if (!(Test-Path -LiteralPath $destination) -or
            (Get-FileHash -LiteralPath $destination -Algorithm SHA256).Hash -ne $row.binarySha256) {
            throw "Recompiled SPIR-V differs from the checked binary: $($row.binary)"
        }
    } else { Copy-Item -LiteralPath (Join-Path $outputDir $row.binary) -Destination $destination -Force }
}
if (!$Check) {
    $xml = [System.Collections.Generic.List[string]]::new()
    $xml.Add('<Project>')
    $xml.Add('  <!-- Generated by tools/Compile-Shaders.ps1 after compilation and spirv-val. -->')
    $xml.Add('  <ItemGroup>')
    foreach ($row in $rows) {
        foreach ($kind in @('source', 'binary')) {
            $filename = $row[$kind]
            $hash = $row[$kind + 'Sha256']
            $xml.Add('    <VerifiedShader Include="$(MSBuildThisFileDirectory)' + $filename + '" ExpectedHash="' + $hash + '" />')
        }
    }
    $xml.Add('  </ItemGroup>')
    $xml.Add('</Project>')
    [IO.File]::WriteAllText((Join-Path $shaderDir 'ShaderHashes.props'), ($xml -join "`n") + "`n", [Text.UTF8Encoding]::new($false))
}
$receipt = [ordered]@{ schemaVersion = 1; checkedAtUtc = [DateTime]::UtcNow.ToString('O'); checkOnly = [bool]$Check;
    targetEnvironment = 'vulkan1.0'; compiler = $Compiler; compilerVersion = $compilerVersion;
    validator = $Validator; validatorVersion = $validatorVersion; wslDistribution = $WslDistribution; shaders = $rows }
$receipt | ConvertTo-Json -Depth 5 | Set-Content -LiteralPath (Join-Path $outputDir 'receipt.json') -Encoding utf8
Write-Output "All four shaders compiled and validated. Receipt: $outputDir/receipt.json"
