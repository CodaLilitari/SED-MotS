#requires -Version 7.2
<#
.SYNOPSIS
Exercises static MotS lighting through the agent CLI, synthetic archives and Vulkan.
.DESCRIPTION
Builds original synthetic JKL, 8-bit MAT, full CMP and 3DO data in a new directory.
Checks independent surface and architectural mono/RGB rendering, exact resource
provenance, strict/permissive asset handling and refusal to replace existing PNGs.
Also checks resource validation and reviewed plan/apply/convert using a separate
closed synthetic room, including changed resources that leave output JKL unchanged.
Separately checks world-occluded ARCH baking against a ceiling/NoBlock control,
analytic independent mono/RGB samples and saved profile/resource provenance.
Starts only direct bounded agent processes, with no GUI, game, shell or network.
Requires an agent build that supports lit snapshots and a working Vulkan device.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$AgentPath,
    [Parameter(Mandatory)][string]$OutputDirectory
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$utf8 = [Text.UTF8Encoding]::new($false, $true)
$agent = (Resolve-Path -LiteralPath $AgentPath).ProviderPath
if (-not (Test-Path -LiteralPath $agent -PathType Leaf)) { throw 'AgentPath must name an executable file.' }
$scratch = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($OutputDirectory)
if (Test-Path -LiteralPath $scratch) { throw 'OutputDirectory must be new; existing paths are never reused.' }
if (-not (Test-Path -LiteralPath (Split-Path -Parent $scratch) -PathType Container)) { throw 'The parent of OutputDirectory must exist.' }
$null = New-Item -ItemType Directory -Path $scratch -ErrorAction Stop
$receipt = [ordered]@{
    schemaVersion = 1; startedUtc = [DateTime]::UtcNow.ToString('o'); status = 'running'
    agentPath = $agent; agentSha256 = (Get-FileHash -LiteralPath $agent -Algorithm SHA256).Hash.ToLowerInvariant()
    outputDirectory = $scratch; guiLaunched = $false; gameLaunched = $false; shellChildLaunched = $false
    processTimeoutSeconds = 30; imageVisuallyInspected = $false
    assetProvenance = 'Original synthetic data generated by this script; no game or community assets.'
    limitations = @('Static offscreen editor lighting only; no dynamic lights, COG, animations or gameplay.',
        'Pixel comparisons use the same host/device; image bytes are not a cross-driver golden reference.',
        'The fixture is an open scene for rendering, not a complete playable episode.')
    fixtures = [Collections.Generic.List[object]]::new()
    steps = [Collections.Generic.List[object]]::new()
    checks = [Collections.Generic.List[object]]::new()
    outputs = [Collections.Generic.List[object]]::new()
}
function Get-Hash([string]$Path) { (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash.ToLowerInvariant() }
function Get-BytesHash([byte[]]$Bytes) { [Convert]::ToHexString([Security.Cryptography.SHA256]::HashData($Bytes)).ToLowerInvariant() }
function Convert-Request($Value) { ConvertTo-Json -InputObject $Value -Depth 50 -Compress }
function Confirm-Check([string]$Name, [bool]$Condition) {
    $receipt.checks.Add([ordered]@{ name = $Name; passed = $Condition })
    if (-not $Condition) { throw "Lighting snapshot assertion failed: $Name" }
}
function Write-NewBytes([string]$Path, [byte[]]$Bytes) {
    $stream = [IO.FileStream]::new($Path, [IO.FileMode]::CreateNew, [IO.FileAccess]::Write, [IO.FileShare]::None)
    try { $stream.Write($Bytes, 0, $Bytes.Length); $stream.Flush($true) } finally { $stream.Dispose() }
}
function Invoke-Agent {
    param([string]$Name, [string[]]$Arguments, [AllowEmptyString()][string]$InputText = '', [int]$ExpectedExit = 0)
    $stem = '{0:D2}-{1}' -f ($receipt.steps.Count + 1), $Name
    $inputBytes = $utf8.GetBytes($InputText)
    $step = [ordered]@{
        name = $Name; executable = $agent; arguments = $Arguments
        stdinFile = $(if ($InputText.Length) { "$stem.request.json" } else { "$stem.stdin.txt" })
        stdinBytes = $inputBytes.Length; stdinSha256 = Get-BytesHash $inputBytes
        expectedExitCode = $ExpectedExit; exitCode = $null; timedOut = $false
        stdoutFile = "$stem.stdout.json"; stderrFile = "$stem.stderr.txt"; stdoutJson = $null; passed = $false
    }
    Write-NewBytes (Join-Path $scratch $step.stdinFile) $inputBytes
    $receipt.steps.Add($step)
    $start = [Diagnostics.ProcessStartInfo]::new()
    $start.FileName = $agent; $start.WorkingDirectory = $scratch
    $start.UseShellExecute = $false; $start.CreateNoWindow = $true
    $start.RedirectStandardInput = $true; $start.RedirectStandardOutput = $true; $start.RedirectStandardError = $true
    $start.StandardInputEncoding = $utf8; $start.StandardOutputEncoding = $utf8; $start.StandardErrorEncoding = $utf8
    foreach ($argument in $Arguments) { $start.ArgumentList.Add($argument) }
    $process = [Diagnostics.Process]::new(); $process.StartInfo = $start
    $clock = [Diagnostics.Stopwatch]::StartNew()
    $started = $false; $stdoutTask = $null; $stderrTask = $null
    try {
        $started = $process.Start()
        if (-not $started) { throw "Could not start agent for $Name." }
        $stdoutTask = $process.StandardOutput.ReadToEndAsync(); $stderrTask = $process.StandardError.ReadToEndAsync()
        try {
            $writeTask = $process.StandardInput.BaseStream.WriteAsync($inputBytes, 0, $inputBytes.Length)
            if (-not $writeTask.Wait([Math]::Max(0, 30000 - [int]$clock.ElapsedMilliseconds))) {
                $step.timedOut = $true; throw 'Agent stdin write timed out.'
            }
            $null = $writeTask.GetAwaiter().GetResult()
        }
        catch { $step.stdinWriteError = $_.Exception.GetBaseException().Message; if ($step.timedOut) { throw } }
        finally { $process.StandardInput.Close() }
        if (-not $process.WaitForExit([Math]::Max(0, 30000 - [int]$clock.ElapsedMilliseconds))) {
            $step.timedOut = $true; throw "Agent process timed out: $Name"
        }
        $step.exitCode = $process.ExitCode
        $stdout = $stdoutTask.GetAwaiter().GetResult(); $stderr = $stderrTask.GetAwaiter().GetResult()
        [IO.File]::WriteAllText((Join-Path $scratch $step.stdoutFile), $stdout, $utf8)
        [IO.File]::WriteAllText((Join-Path $scratch $step.stderrFile), $stderr, $utf8)
        $parsed = ConvertFrom-Json -InputObject $stdout -AsHashtable -Depth 100 -ErrorAction Stop
        if ($parsed -isnot [Collections.IDictionary]) { throw "Agent stdout must be one JSON object: $Name" }
        $step.stdoutJson = $parsed
        if ($step.exitCode -ne $ExpectedExit) { throw "Agent $Name returned $($step.exitCode); expected $ExpectedExit. See $($step.stdoutFile)." }
        if ($stderr.Length) { throw "Unexpected stderr from $Name. See $($step.stderrFile)." }
        $step.passed = $true
        return $parsed
    }
    finally {
        if ($started -and -not $process.HasExited) { $process.Kill($true); $null = $process.WaitForExit(5000) }
        if ($null -ne $stdoutTask -and $stdoutTask.IsCompletedSuccessfully) {
            [IO.File]::WriteAllText((Join-Path $scratch $step.stdoutFile), $stdoutTask.GetAwaiter().GetResult(), $utf8)
        }
        if ($null -ne $stderrTask -and $stderrTask.IsCompletedSuccessfully) {
            [IO.File]::WriteAllText((Join-Path $scratch $step.stderrFile), $stderrTask.GetAwaiter().GetResult(), $utf8)
        }
        $step.elapsedMilliseconds = $clock.ElapsedMilliseconds; $process.Dispose()
    }
}
function New-SyntheticMat {
    $memory = [IO.MemoryStream]::new(); $writer = [IO.BinaryWriter]::new($memory)
    try {
        $writer.Write([Text.Encoding]::ASCII.GetBytes('MAT '))
        foreach ($value in @(0x32, 2, 1, 1, 0, 8)) { $writer.Write([int]$value) }
        $writer.Write([byte[]]::new(12 * 4)) # Remaining ColorInfo fields.
        $writer.Write([byte[]]::new(40)) # One texture cel header, texture index zero.
        foreach ($value in @(2, 2, 0, 0, 0, 1)) { $writer.Write([int]$value) }
        $writer.Write([byte[]]@(1, 1, 1, 1))
        $writer.Flush(); return ,$memory.ToArray()
    }
    finally { $writer.Dispose(); $memory.Dispose() }
}
function New-SyntheticCmp {
    $bytes = [byte[]]::new(64 + 768 + 16384)
    [Text.Encoding]::ASCII.GetBytes('CMP ').CopyTo($bytes, 0)
    ([byte[]]@(200, 160, 100)).CopyTo($bytes, 67) # Base palette entry 1.
    ([byte[]]@(20, 40, 160)).CopyTo($bytes, 70) # Deliberately colored dim-light ramp entry.
    for ($row = 0; $row -lt 64; $row++) {
        for ($index = 0; $index -lt 256; $index++) {
            $bytes[832 + $row * 256 + $index] = if ($row -lt 32 -and $index -eq 1) { 2 } else { $index }
        }
    }
    return ,$bytes
}
function New-SyntheticGob([Collections.IDictionary]$Entries) {
    $memory = [IO.MemoryStream]::new(); $writer = [IO.BinaryWriter]::new($memory)
    try {
        $writer.Write([Text.Encoding]::ASCII.GetBytes('GOB ')); $writer.Write([uint32]0x14); $writer.Write([uint32]12)
        $writer.Write([uint32]$Entries.Count)
        $cursor = 16 + 136 * $Entries.Count
        foreach ($entry in $Entries.GetEnumerator()) {
            $name = [Text.Encoding]::ASCII.GetBytes([string]$entry.Key)
            if ($name.Length -ge 128) { throw 'Synthetic archive name exceeds the GOB entry limit.' }
            $writer.Write([uint32]$cursor); $writer.Write([uint32]$entry.Value.Length)
            $fixedName = [byte[]]::new(128); $name.CopyTo($fixedName, 0); $writer.Write($fixedName)
            $cursor += $entry.Value.Length
        }
        foreach ($entry in $Entries.GetEnumerator()) { $writer.Write([byte[]]$entry.Value) }
        $writer.Flush(); return ,$memory.ToArray()
    }
    finally { $writer.Dispose(); $memory.Dispose() }
}
function Read-BigEndian([byte[]]$Bytes, [int]$Offset) {
    return [int]([uint32]$Bytes[$Offset] * 16777216 + [uint32]$Bytes[$Offset + 1] * 65536 +
        [uint32]$Bytes[$Offset + 2] * 256 + [uint32]$Bytes[$Offset + 3])
}
function Read-SnapshotPng([string]$Path) {
    # The repository encoder writes noninterlaced 8-bit RGBA with PNG filter 0.
    # Decode those bytes independently and compare their hash to the CLI receipt.
    $bytes = [IO.File]::ReadAllBytes($Path)
    if ($bytes.Length -lt 33 -or [Convert]::ToHexString($bytes[0..7]) -ne '89504E470D0A1A0A') { throw 'Invalid snapshot PNG signature.' }
    $compressed = [IO.MemoryStream]::new(); $offset = 8; $width = 0; $height = 0; $ended = $false
    try {
        while ($offset + 12 -le $bytes.Length) {
            $length = Read-BigEndian $bytes $offset
            if ($length -lt 0 -or $offset + 12L + $length -gt $bytes.Length) { throw 'PNG chunk exceeds file bounds.' }
            $kind = [Text.Encoding]::ASCII.GetString($bytes, $offset + 4, 4)
            if ($kind -eq 'IHDR') {
                if ($length -ne 13) { throw 'Invalid PNG header size.' }
                $width = Read-BigEndian $bytes ($offset + 8); $height = Read-BigEndian $bytes ($offset + 12)
                if ($width -lt 1 -or $height -lt 1 -or $width * [long]$height -gt 2097152 -or
                    $bytes[$offset + 16] -ne 8 -or $bytes[$offset + 17] -ne 6 -or $bytes[$offset + 20] -ne 0) {
                    throw 'Expected bounded noninterlaced 8-bit RGBA PNG.'
                }
            }
            elseif ($kind -eq 'IDAT') { $compressed.Write($bytes, $offset + 8, $length) }
            elseif ($kind -eq 'IEND') { $ended = $true; break }
            $offset += 12 + $length
        }
        if (-not $ended -or $width -eq 0) { throw 'Incomplete snapshot PNG.' }
        $compressed.Position = 0
        $zlib = [IO.Compression.ZLibStream]::new($compressed, [IO.Compression.CompressionMode]::Decompress, $true)
        $stride = $width * 4; $raw = [byte[]]::new(($stride + 1) * $height)
        try {
            $read = 0
            while ($read -lt $raw.Length) {
                $count = $zlib.Read($raw, $read, $raw.Length - $read)
                if ($count -eq 0) { throw 'Truncated snapshot pixel data.' }; $read += $count
            }
            if ($zlib.ReadByte() -ne -1) { throw 'Unexpected trailing decompressed pixel data.' }
        }
        finally { $zlib.Dispose() }
        $pixels = [byte[]]::new($stride * $height)
        for ($row = 0; $row -lt $height; $row++) {
            if ($raw[$row * ($stride + 1)] -ne 0) { throw 'Snapshot encoder changed PNG row filters; update this bounded decoder.' }
            [Array]::Copy($raw, $row * ($stride + 1) + 1, $pixels, $row * $stride, $stride)
        }
        return @{ width = $width; height = $height; rgbaSha256 = Get-BytesHash $pixels; pixels = $pixels }
    }
    finally { $compressed.Dispose() }
}
function Count-PixelColor([byte[]]$Pixels, [int[]]$Rgb) {
    $matches = 0
    for ($index = 0; $index -lt $Pixels.Length; $index += 4) {
        if ([Math]::Abs([int]$Pixels[$index] - $Rgb[0]) -le 1 -and
            [Math]::Abs([int]$Pixels[$index + 1] - $Rgb[1]) -le 1 -and
            [Math]::Abs([int]$Pixels[$index + 2] - $Rgb[2]) -le 1 -and $Pixels[$index + 3] -eq 255) { $matches++ }
    }
    return $matches
}
function New-SnapshotRequest($Inspection, [string]$Mode = 'diagnostic', [string]$Lighting = 'game', [string]$Archive = '', [string]$ArchiveHash = '') {
    $request = [ordered]@{ schemaVersion = 1; inputSha256 = $Inspection.inputSha256; sourceRevision = $Inspection.sourceRevision
        position = @(0, -3, 4); target = @(0, 0, 0); fieldOfViewDegrees = 65; width = 256; height = 192
        nearPlane = 0.01; farPlane = 100; mode = $Mode }
    if ($Mode -eq 'lit') { $request.lightingMode = $Lighting; $request.resourceArchives = @(@{ path = $Archive; sha256 = $ArchiveHash }) }
    if ($Mode -eq 'lit' -and $Lighting -eq 'mono') { $request.renderProfile = 'palette' }
    return $request
}
function Invoke-Snapshot([string]$Name, [string]$LevelPath, $Request) {
    $requestText = Convert-Request $Request
    $path = Join-Path $scratch "$Name.png"
    $result = Invoke-Agent $Name @('snapshot', $LevelPath, '-', $path) $requestText
    Confirm-Check "$Name reports the output hash and byte count" ((Get-Hash $path) -eq $result.outputSha256 -and (Get-Item -LiteralPath $path).Length -eq $result.outputBytes)
    Confirm-Check "$Name binds source, revision and exact request" ($result.inputSha256 -eq $Request.inputSha256 -and $result.sourceRevision -eq $Request.sourceRevision -and $result.requestSha256 -eq (Get-BytesHash $utf8.GetBytes($requestText)))
    Confirm-Check "$Name uses an offscreen explicit camera" (-not $result.guiLaunched -and $result.camera.up -eq 'Z' -and $result.cameraSha256 -match '^[0-9a-f]{64}$' -and
        ($result.camera.position -join ',') -eq ($Request.position -join ',') -and ($result.camera.target -join ',') -eq ($Request.target -join ',') -and
        $result.camera.fieldOfViewDegrees -eq $Request.fieldOfViewDegrees -and $result.camera.nearPlane -eq $Request.nearPlane -and $result.camera.farPlane -eq $Request.farPlane)
    $image = Read-SnapshotPng $path
    Confirm-Check "$Name PNG dimensions and independently decoded pixels match" ($image.width -eq $Request.width -and $image.height -eq $Request.height -and $image.rgbaSha256 -eq $result.rgbaSha256)
    Confirm-Check "$Name contains visible geometry" ($result.nonBackgroundPixels -gt 100)
    $receipt.outputs.Add([ordered]@{ name = $Name; path = $path; sha256 = $result.outputSha256; rgbaSha256 = $result.rgbaSha256
        width = $image.width; height = $image.height; counts = $result.counts; warnings = $result.warnings })
    return @{ result = $result; image = $image; path = $path }
}
function Invoke-ArchitectureAuthoringWorkflow([string]$Source, $Inspection, $Archives) {
    $patch = [ordered]@{ schemaVersion = 1; inputSha256 = $Inspection.inputSha256; resourceArchives = $Archives
        operations = @(
            @{ op = 'addLight'; position = @(-0.6, -0.6, 1.2); rgb = @(1, 0.5, 0.25); intensity = 0.8; rgbIntensity = 0.4; range = 2 },
            @{ op = 'bakeThingArchitecture'; thing = 0; profile = 'source-points-v1' }) }
    $schema = Invoke-Agent 'architecture-bake-schema' @('schema', 'bakeThingArchitecture')
    Confirm-Check 'bake schema names the bounded profile' ((Convert-Request $schema) -match 'source-points-v1')
    $plan = Invoke-Agent 'plan-architecture-bake' @('plan', $Source, '-') (Convert-Request $patch)
    $effect = $plan.changes[1].serializedFinal.state
    Confirm-Check 'bake appends private arrays and records captured model plus local input state' (
        $effect.archLightingIndex -eq 1 -and $effect.architecture.status -eq 'current-inputs' -and
        $effect.architecture.provenance.origin -eq 'source-points-v1' -and
        $effect.architecture.provenance.modelSha256 -match '^[0-9a-f]{64}$' -and
        $plan.after.architecturalObjects -eq 2)
    $patch.resourceRevision = $plan.resourceRevision
    $baked = Join-Path $scratch 'architecture-baked.jkl'
    $null = Invoke-Agent 'apply-architecture-bake' @('apply', $Source, '-', $baked, $plan.outputSha256) (Convert-Request $patch)
    Confirm-Check 'baked document matches the reviewed bytes' ((Get-Hash $baked) -eq $plan.outputSha256)
    $things = Invoke-Agent 'query-baked-thing' @('query', $baked, '-') '{"schemaVersion":1,"collection":"things"}'
    Confirm-Check 'saved provenance remains locally current without asserting resource freshness' (
        $things.items[0].architecture.status -eq 'current-inputs' -and
        $things.items[0].architecture.resourceStatus -eq 'unverified-use-resource-validation')
    $samples = Invoke-Agent 'query-baked-samples' @('query', $baked, '-') '{"schemaVersion":1,"collection":"architecturalVertices","lightingIndex":1,"mesh":0,"limit":2}'
    Confirm-Check 'samples are paginated with analytic independent white RGB values' (
        $samples.total -eq 4 -and $samples.nextOffset -eq 2 -and $samples.returnedCount -eq 2 -and
        [Math]::Abs($samples.items[0].mono - 0.2) -lt 1e-12 -and
        [Math]::Abs($samples.items[0].rgb[0] - 0.1) -lt 1e-12 -and
        [Math]::Abs($samples.items[0].rgb[1] - 0.05) -lt 1e-12 -and
        [Math]::Abs($samples.items[0].rgb[2] - 0.025) -lt 1e-12)
    $old = Invoke-Agent 'query-preserved-old-architecture' @('query', $baked, '-') '{"schemaVersion":1,"collection":"architecturalVertices","lightingIndex":0,"mesh":0}'
    Confirm-Check 'bake leaves the original allocation untouched' ($old.items[0].mono -eq 0.9 -and $old.items[0].rgb[2] -eq 0.8)
    $catalog = Invoke-Agent 'query-architecture-catalog' @('query', $baked, '-') '{"schemaVersion":1,"collection":"architecture"}'
    Confirm-Check 'catalog exposes orphan and bound arrays without silently compacting them' (
        $catalog.items.Count -eq 2 -and $catalog.items[0].boundThings.Count -eq 0 -and $catalog.items[1].boundThings[0] -eq 0)
    $bakedInspection = Invoke-Agent 'inspect-baked-architecture' @('inspect', $baked)
    # The closed transaction room needs an interior camera. The open-scene
    # default sits outside it and only sees an opaque wall. Hold the material
    # profile fixed and compare before/after arrays with unchanged world lighting.
    $rgbRequest = New-SnapshotRequest $bakedInspection 'lit' 'rgb' $Archives[0].path $Archives[0].sha256
    $rgbRequest.position = @(0, -1.4, 2); $rgbRequest.target = @(0, 0, 0.2); $rgbRequest.renderProfile = 'openjk'
    $monoRequest = ConvertFrom-Json -InputObject (Convert-Request $rgbRequest) -AsHashtable -Depth 50
    $monoRequest.lightingMode = 'mono'
    $beforeRequest = ConvertFrom-Json -InputObject (Convert-Request $rgbRequest) -AsHashtable -Depth 50
    $beforeRequest.inputSha256 = $Inspection.inputSha256; $beforeRequest.sourceRevision = $Inspection.sourceRevision
    $before = Invoke-Snapshot 'authored-architecture-before' $Source $beforeRequest
    $rgb = Invoke-Snapshot 'authored-architecture-rgb' $baked $rgbRequest
    $mono = Invoke-Snapshot 'authored-architecture-mono' $baked $monoRequest
    Confirm-Check 'new architectural samples visibly change the fixed-profile scene' ($rgb.result.rgbaSha256 -ne $before.result.rgbaSha256)
    Confirm-Check 'authored channel comparison keeps camera and material profile fixed' (
        $rgb.result.rgbaSha256 -ne $mono.result.rgbaSha256 -and $rgb.result.renderProfile -eq 'openjk' -and
        $mono.result.renderProfile -eq 'openjk' -and $rgb.result.cameraSha256 -eq $mono.result.cameraSha256)
    $stalePatch = @{ schemaVersion = 1; inputSha256 = $bakedInspection.inputSha256
        operations = @(@{ op = 'setLight'; light = 0; rgbIntensity = 0 }) }
    $stale = Join-Path $scratch 'architecture-stale.jkl'
    $null = Invoke-Agent 'save-stale-architecture' @('apply', $baked, '-', $stale) (Convert-Request $stalePatch)
    $staleThings = Invoke-Agent 'query-stale-architecture' @('query', $stale, '-') '{"schemaVersion":1,"collection":"things"}'
    Confirm-Check 'source edit preserves samples but makes the recorded bake stale' (
        $staleThings.items[0].architecture.status -eq 'stale' -and
        $staleThings.items[0].architecture.samplesSha256 -eq $things.items[0].architecture.samplesSha256)
    $resetPatch = @{ schemaVersion = 1; inputSha256 = $Inspection.inputSha256; resourceArchives = $Archives
        operations = @(@{ op = 'rebindThingArchitecture'; thing = 0; policy = 'reset' }) }
    $reset = Invoke-Agent 'plan-explicit-architecture-reset' @('plan', $Source, '-') (Convert-Request $resetPatch)
    Confirm-Check 'explicit reset is not described as baked' ($reset.changes[0].serializedFinal.state.architecture.status -eq 'reset')
    $bindPatch = @{ schemaVersion = 1; inputSha256 = $Inspection.inputSha256; resourceArchives = $Archives
        operations = @(@{ op = 'clearThingArchitecture'; thing = 0 }, @{ op = 'bindThingArchitecture'; thing = 0; lightingIndex = 0 }) }
    $bind = Invoke-Agent 'plan-architecture-bind' @('plan', $Source, '-') (Convert-Request $bindPatch)
    Confirm-Check 'binding retained samples does not invent fresh bake provenance' ($bind.changes[1].serializedFinal.state.architecture.status -eq 'bound')
    $missing = @{ schemaVersion = 1; inputSha256 = $Inspection.inputSha256
        operations = @(@{ op = 'bakeThingArchitecture'; thing = 0; profile = 'source-points-v1' }) }
    $refusedPath = Join-Path $scratch 'must-not-bake-without-resources.jkl'
    $refusal = Invoke-Agent 'refuse-bake-without-resources' @('apply', $Source, '-', $refusedPath) (Convert-Request $missing) 2
    Confirm-Check 'resource-free bake refuses with operation diagnostics and no output' (
        -not (Test-Path -LiteralPath $refusedPath) -and $refusal.details.operationIndex -eq 0)
    foreach ($path in @($baked, $stale)) { $receipt.outputs.Add(@{name='architecture-authoring-jkl';path=$path;sha256=Get-Hash $path;kind='jkl'}) }
    $receipt.architectureAuthoring = @{ profile = 'source-points-v1'; shadows = $false; directionalNormals = $false
        sourcePath = $Source; bakedPath = $baked; stalePath = $stale; resourceRevision = $plan.resourceRevision }
}
function Invoke-WorldOccludedArchitectureWorkflow([string]$ClosedText, [Collections.IDictionary]$Entries) {
    $profile = 'source-points-world-occluded-v1'
    $schema = Invoke-Agent 'world-occluded-bake-schema' @('schema', 'bakeThingArchitecture')
    Confirm-Check 'bake schema explicitly supports the world-occluded profile' (
        $profile -in $schema.properties.operations.items.oneOf[0].properties.profile.enum)

    # Keep separate immutable inputs: the resource workflow later mutates its
    # own archive. The source is above the closed room's ceiling at z=3; every
    # panel sample is inside at z=.2. Thus every ray crosses the ceiling, while
    # NoBlock=1 deliberately bypasses it. No model/material/runtime claim follows.
    $source = Join-Path $scratch 'world-occluded-source.jkl'
    $archive = Join-Path $scratch 'world-occluded-original.gob'
    Write-NewBytes $source $utf8.GetBytes($ClosedText)
    Write-NewBytes $archive (New-SyntheticGob $Entries)
    foreach ($path in @($source, $archive)) {
        $receipt.fixtures.Add(@{ path = $path; sha256 = Get-Hash $path; bytes = (Get-Item -LiteralPath $path).Length })
    }
    $inspection = Invoke-Agent 'inspect-world-occluded-source' @('inspect', $source)
    $archives = @(@{ path = $archive; sha256 = Get-Hash $archive })
    $modelHash = Get-BytesHash $Entries['3do\agent_lit.3do']
    $cases = @(
        @{ name = 'blocked'; flags = 0; mono = 0.8; color = 0.4; expected = @(0, 0, 0, 0) },
        @{ name = 'noblock'; flags = 1; mono = 0.8; color = 0.4; expected = @(0.2, 0.1, 0.05, 0.025) },
        @{ name = 'mono-only'; flags = 1; mono = 0.8; color = 0; expected = @(0.2, 0, 0, 0) },
        @{ name = 'rgb-only'; flags = 1; mono = 0; color = 0.4; expected = @(0, 0.1, 0.05, 0.025) })
    $records = [Collections.Generic.List[object]]::new()
    foreach ($case in $cases) {
        $name = 'world-occluded-' + $case.name
        $patch = [ordered]@{ schemaVersion = 1; inputSha256 = $inspection.inputSha256
            sourceRevision = $inspection.sourceRevision; resourceArchives = $archives
            operations = @(
                @{ op = 'addLight'; position = @(-0.6, -0.6, 4.2); rgb = @(1, 0.5, 0.25)
                    intensity = $case.mono; rgbIntensity = $case.color; range = 8; flags = $case.flags },
                @{ op = 'bakeThingArchitecture'; thing = 0; profile = $profile }) }
        $plan = Invoke-Agent "plan-$name" @('plan', $source, '-') (Convert-Request $patch)
        $effect = $plan.changes[1].serializedFinal.state
        Confirm-Check "$name appends a private array with exact model/profile provenance" (
            $effect.archLightingIndex -eq 1 -and $plan.after.architecturalObjects -eq 2 -and
            $effect.architecture.status -eq 'current-inputs' -and $effect.architecture.provenance.origin -eq $profile -and
            $effect.architecture.provenance.modelSha256 -eq $modelHash -and
            $effect.architecture.provenance.inputSha256 -match '^[0-9a-f]{64}$' -and
            $effect.architecture.provenance.samplesSha256 -match '^[0-9a-f]{64}$')
        $patch.resourceRevision = $plan.resourceRevision
        $output = Join-Path $scratch "$name.jkl"
        $applied = Invoke-Agent "apply-$name" @('apply', $source, '-', $output, $plan.outputSha256) (Convert-Request $patch)
        Confirm-Check "$name applies the reviewed document and resource revisions" (
            (Get-Hash $output) -eq $plan.outputSha256 -and $applied.plan.resourceRevision -eq $plan.resourceRevision)

        $things = Invoke-Agent "query-$name-provenance" @('query', $output, '-') '{"schemaVersion":1,"collection":"things"}'
        $saved = $things.items[0].architecture
        Confirm-Check "$name retains exact provenance and local freshness after save/reopen" (
            $saved.status -eq 'current-inputs' -and $saved.resourceStatus -eq 'unverified-use-resource-validation' -and
            $saved.provenance.origin -eq $profile -and $saved.provenance.modelSha256 -eq $modelHash -and
            $saved.provenance.inputSha256 -eq $effect.architecture.provenance.inputSha256 -and
            $saved.provenance.samplesSha256 -eq $effect.architecture.provenance.samplesSha256)
        $samples = Invoke-Agent "query-$name-samples" @('query', $output, '-') '{"schemaVersion":1,"collection":"architecturalVertices","lightingIndex":1,"mesh":0,"limit":4}'
        # First sample (-.6,-.6,.2) is exactly four units from the source.
        # Range eight gives (1 - 4/8)^2 = 1/4, independently for white and RGB.
        Confirm-Check "$name reads all four samples with the analytic first sample" (
            $samples.total -eq 4 -and $samples.returnedCount -eq 4 -and $null -eq $samples.nextOffset -and
            [Math]::Abs($samples.items[0].mono - $case.expected[0]) -lt 1e-12 -and
            [Math]::Abs($samples.items[0].rgb[0] - $case.expected[1]) -lt 1e-12 -and
            [Math]::Abs($samples.items[0].rgb[1] - $case.expected[2]) -lt 1e-12 -and
            [Math]::Abs($samples.items[0].rgb[2] - $case.expected[3]) -lt 1e-12)
        $unexpected = @($samples.items | Where-Object {
            ($case.flags -eq 0 -and ($_.mono -ne 0 -or $_.rgb[0] -ne 0 -or $_.rgb[1] -ne 0 -or $_.rgb[2] -ne 0)) -or
            ($case.flags -eq 1 -and $case.mono -gt 0 -and $_.mono -le 0) -or
            ($case.mono -eq 0 -and $_.mono -ne 0) -or
            ($case.flags -eq 1 -and $case.color -gt 0 -and ($_.rgb[0] -le 0 -or $_.rgb[1] -le 0 -or $_.rgb[2] -le 0)) -or
            ($case.color -eq 0 -and ($_.rgb[0] -ne 0 -or $_.rgb[1] -ne 0 -or $_.rgb[2] -ne 0)) })
        Confirm-Check "$name obeys ceiling occlusion and independent channels at every sample" ($unexpected.Count -eq 0)
        $lights = Invoke-Agent "query-$name-light" @('query', $output, '-') '{"schemaVersion":1,"collection":"lights"}'
        Confirm-Check "$name preserves the explicit source flags and independent intensity values" (
            $lights.total -eq 1 -and $lights.items[0].flags -eq $case.flags -and
            $lights.items[0].intensity -eq $case.mono -and $lights.items[0].rgbIntensity -eq $case.color -and
            $lights.items[0].effectiveRgbIntensity -eq $case.color -and -not $lights.items[0].rgbIntensityInherited)
        $receipt.outputs.Add(@{ name = $name; path = $output; sha256 = Get-Hash $output; kind = 'jkl' })
        $records.Add(@{ name = $case.name; path = $output; firstSample = $samples.items[0]
            provenance = $saved.provenance; resourceRevision = $plan.resourceRevision })
    }
    Confirm-Check 'world occlusion and NoBlock comparison binds differing inputs and samples' (
        $records[0].provenance.inputSha256 -ne $records[1].provenance.inputSha256 -and
        $records[0].provenance.samplesSha256 -ne $records[1].provenance.samplesSha256)
    $receipt.worldOccludedArchitecture = @{ profile = $profile; sourcePath = $source; archivePath = $archive
        sourcePosition = @(-0.6, -0.6, 4.2); firstSamplePosition = @(-0.6, -0.6, 0.2)
        ceilingZ = 3; range = 8; unblockedFirstSampleFalloff = 0.25; cases = $records
        limits = 'Editor world-polygon recipe only; no material-alpha, model/self shadow, runtime or retail equivalence claim.' }
}
