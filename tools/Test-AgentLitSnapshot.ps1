#requires -Version 7.2
<#
.SYNOPSIS
Exercises static MotS lighting through the agent CLI, synthetic archives and Vulkan.
.DESCRIPTION
Builds original synthetic JKL, 8-bit MAT, full CMP and 3DO data in a new directory.
Checks independent surface and architectural mono/RGB rendering, exact resource
provenance, strict/permissive asset handling and refusal to replace existing PNGs.
Starts only direct bounded agent processes, with no GUI, game, shell or network.
Requires an agent build that supports lit snapshots and a working Vulkan device.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$AgentPath,
    [Parameter(Mandatory)][string]$OutputDirectory
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$utf8 = [Text.UTF8Encoding]::new($false, $true)
$agent = (Resolve-Path -LiteralPath $AgentPath).ProviderPath
if (-not (Test-Path -LiteralPath $agent -PathType Leaf)) { throw 'AgentPath must name an executable file.' }
$scratch = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($OutputDirectory)
if (Test-Path -LiteralPath $scratch) { throw 'OutputDirectory must be new; existing paths are never reused.' }
if (-not (Test-Path -LiteralPath (Split-Path -Parent $scratch) -PathType Container)) { throw 'The parent of OutputDirectory must exist.' }
$null = New-Item -ItemType Directory -Path $scratch -ErrorAction Stop
$receipt = [ordered]@{
    schemaVersion = 1; startedUtc = [DateTime]::UtcNow.ToString('o'); status = 'running'
    agentPath = $agent; agentSha256 = (Get-FileHash -LiteralPath $agent -Algorithm SHA256).Hash.ToLowerInvariant()
    outputDirectory = $scratch; guiLaunched = $false; gameLaunched = $false; shellChildLaunched = $false
    processTimeoutSeconds = 30; imageVisuallyInspected = $false
    assetProvenance = 'Original synthetic data generated by this script; no game or community assets.'
    limitations = @('Static offscreen editor lighting only; no dynamic lights, COG, animations or gameplay.',
        'Pixel comparisons use the same host/device; image bytes are not a cross-driver golden reference.',
        'The fixture is an open scene for rendering, not a complete playable episode.')
    fixtures = [Collections.Generic.List[object]]::new()
    steps = [Collections.Generic.List[object]]::new()
    checks = [Collections.Generic.List[object]]::new()
    outputs = [Collections.Generic.List[object]]::new()
}
function Get-Hash([string]$Path) { (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash.ToLowerInvariant() }
function Get-BytesHash([byte[]]$Bytes) { [Convert]::ToHexString([Security.Cryptography.SHA256]::HashData($Bytes)).ToLowerInvariant() }
function Convert-Request($Value) { ConvertTo-Json -InputObject $Value -Depth 50 -Compress }
function Confirm-Check([string]$Name, [bool]$Condition) {
    $receipt.checks.Add([ordered]@{ name = $Name; passed = $Condition })
    if (-not $Condition) { throw "Lighting snapshot assertion failed: $Name" }
}
function Write-NewBytes([string]$Path, [byte[]]$Bytes) {
    $stream = [IO.FileStream]::new($Path, [IO.FileMode]::CreateNew, [IO.FileAccess]::Write, [IO.FileShare]::None)
    try { $stream.Write($Bytes, 0, $Bytes.Length); $stream.Flush($true) } finally { $stream.Dispose() }
}
function Invoke-Agent {
    param([string]$Name, [string[]]$Arguments, [AllowEmptyString()][string]$InputText = '', [int]$ExpectedExit = 0)
    $stem = '{0:D2}-{1}' -f ($receipt.steps.Count + 1), $Name
    $inputBytes = $utf8.GetBytes($InputText)
    $step = [ordered]@{
        name = $Name; executable = $agent; arguments = $Arguments
        stdinFile = $(if ($InputText.Length) { "$stem.request.json" } else { "$stem.stdin.txt" })
        stdinBytes = $inputBytes.Length; stdinSha256 = Get-BytesHash $inputBytes
        expectedExitCode = $ExpectedExit; exitCode = $null; timedOut = $false
        stdoutFile = "$stem.stdout.json"; stderrFile = "$stem.stderr.txt"; stdoutJson = $null; passed = $false
    }
    Write-NewBytes (Join-Path $scratch $step.stdinFile) $inputBytes
    $receipt.steps.Add($step)
    $start = [Diagnostics.ProcessStartInfo]::new()
    $start.FileName = $agent; $start.WorkingDirectory = $scratch
    $start.UseShellExecute = $false; $start.CreateNoWindow = $true
    $start.RedirectStandardInput = $true; $start.RedirectStandardOutput = $true; $start.RedirectStandardError = $true
    $start.StandardInputEncoding = $utf8; $start.StandardOutputEncoding = $utf8; $start.StandardErrorEncoding = $utf8
    foreach ($argument in $Arguments) { $start.ArgumentList.Add($argument) }
    $process = [Diagnostics.Process]::new(); $process.StartInfo = $start
    $clock = [Diagnostics.Stopwatch]::StartNew()
    $started = $false; $stdoutTask = $null; $stderrTask = $null
    try {
        $started = $process.Start()
        if (-not $started) { throw "Could not start agent for $Name." }
        $stdoutTask = $process.StandardOutput.ReadToEndAsync(); $stderrTask = $process.StandardError.ReadToEndAsync()
        try {
            $writeTask = $process.StandardInput.BaseStream.WriteAsync($inputBytes, 0, $inputBytes.Length)
            if (-not $writeTask.Wait([Math]::Max(0, 30000 - [int]$clock.ElapsedMilliseconds))) {
                $step.timedOut = $true; throw 'Agent stdin write timed out.'
            }
            $null = $writeTask.GetAwaiter().GetResult()
        }
        catch { $step.stdinWriteError = $_.Exception.GetBaseException().Message; if ($step.timedOut) { throw } }
        finally { $process.StandardInput.Close() }
        if (-not $process.WaitForExit([Math]::Max(0, 30000 - [int]$clock.ElapsedMilliseconds))) {
            $step.timedOut = $true; throw "Agent process timed out: $Name"
        }
        $step.exitCode = $process.ExitCode
        $stdout = $stdoutTask.GetAwaiter().GetResult(); $stderr = $stderrTask.GetAwaiter().GetResult()
        [IO.File]::WriteAllText((Join-Path $scratch $step.stdoutFile), $stdout, $utf8)
        [IO.File]::WriteAllText((Join-Path $scratch $step.stderrFile), $stderr, $utf8)
        $parsed = ConvertFrom-Json -InputObject $stdout -AsHashtable -Depth 100 -ErrorAction Stop
        if ($parsed -isnot [Collections.IDictionary]) { throw "Agent stdout must be one JSON object: $Name" }
        $step.stdoutJson = $parsed
        if ($step.exitCode -ne $ExpectedExit) { throw "Agent $Name returned $($step.exitCode); expected $ExpectedExit. See $($step.stdoutFile)." }
        if ($stderr.Length) { throw "Unexpected stderr from $Name. See $($step.stderrFile)." }
        $step.passed = $true
        return $parsed
    }
    finally {
        if ($started -and -not $process.HasExited) { $process.Kill($true); $null = $process.WaitForExit(5000) }
        if ($null -ne $stdoutTask -and $stdoutTask.IsCompletedSuccessfully) {
            [IO.File]::WriteAllText((Join-Path $scratch $step.stdoutFile), $stdoutTask.GetAwaiter().GetResult(), $utf8)
        }
        if ($null -ne $stderrTask -and $stderrTask.IsCompletedSuccessfully) {
            [IO.File]::WriteAllText((Join-Path $scratch $step.stderrFile), $stderrTask.GetAwaiter().GetResult(), $utf8)
        }
        $step.elapsedMilliseconds = $clock.ElapsedMilliseconds; $process.Dispose()
    }
}
function New-SyntheticMat {
    $memory = [IO.MemoryStream]::new(); $writer = [IO.BinaryWriter]::new($memory)
    try {
        $writer.Write([Text.Encoding]::ASCII.GetBytes('MAT '))
        foreach ($value in @(0x32, 2, 1, 1, 0, 8)) { $writer.Write([int]$value) }
        $writer.Write([byte[]]::new(12 * 4)) # Remaining ColorInfo fields.
        $writer.Write([byte[]]::new(40)) # One texture cel header, texture index zero.
        foreach ($value in @(2, 2, 0, 0, 0, 1)) { $writer.Write([int]$value) }
        $writer.Write([byte[]]@(1, 1, 1, 1))
        $writer.Flush(); return ,$memory.ToArray()
    }
    finally { $writer.Dispose(); $memory.Dispose() }
}
function New-SyntheticCmp {
    $bytes = [byte[]]::new(64 + 768 + 16384)
    [Text.Encoding]::ASCII.GetBytes('CMP ').CopyTo($bytes, 0)
    ([byte[]]@(200, 160, 100)).CopyTo($bytes, 67) # Base palette entry 1.
    ([byte[]]@(20, 40, 160)).CopyTo($bytes, 70) # Deliberately colored dim-light ramp entry.
    for ($row = 0; $row -lt 64; $row++) {
        for ($index = 0; $index -lt 256; $index++) {
            $bytes[832 + $row * 256 + $index] = if ($row -lt 32 -and $index -eq 1) { 2 } else { $index }
        }
    }
    return ,$bytes
}
function New-SyntheticGob([Collections.IDictionary]$Entries) {
    $memory = [IO.MemoryStream]::new(); $writer = [IO.BinaryWriter]::new($memory)
    try {
        $writer.Write([Text.Encoding]::ASCII.GetBytes('GOB ')); $writer.Write([uint32]0x14); $writer.Write([uint32]12)
        $writer.Write([uint32]$Entries.Count)
        $cursor = 16 + 136 * $Entries.Count
        foreach ($entry in $Entries.GetEnumerator()) {
            $name = [Text.Encoding]::ASCII.GetBytes([string]$entry.Key)
            if ($name.Length -ge 128) { throw 'Synthetic archive name exceeds the GOB entry limit.' }
            $writer.Write([uint32]$cursor); $writer.Write([uint32]$entry.Value.Length)
            $fixedName = [byte[]]::new(128); $name.CopyTo($fixedName, 0); $writer.Write($fixedName)
            $cursor += $entry.Value.Length
        }
        foreach ($entry in $Entries.GetEnumerator()) { $writer.Write([byte[]]$entry.Value) }
        $writer.Flush(); return ,$memory.ToArray()
    }
    finally { $writer.Dispose(); $memory.Dispose() }
}
function Read-BigEndian([byte[]]$Bytes, [int]$Offset) {
    return [int]([uint32]$Bytes[$Offset] * 16777216 + [uint32]$Bytes[$Offset + 1] * 65536 +
        [uint32]$Bytes[$Offset + 2] * 256 + [uint32]$Bytes[$Offset + 3])
}
function Read-SnapshotPng([string]$Path) {
    # The repository encoder writes noninterlaced 8-bit RGBA with PNG filter 0.
    # Decode those bytes independently and compare their hash to the CLI receipt.
    $bytes = [IO.File]::ReadAllBytes($Path)
    if ($bytes.Length -lt 33 -or [Convert]::ToHexString($bytes[0..7]) -ne '89504E470D0A1A0A') { throw 'Invalid snapshot PNG signature.' }
    $compressed = [IO.MemoryStream]::new(); $offset = 8; $width = 0; $height = 0; $ended = $false
    try {
        while ($offset + 12 -le $bytes.Length) {
            $length = Read-BigEndian $bytes $offset
            if ($length -lt 0 -or $offset + 12L + $length -gt $bytes.Length) { throw 'PNG chunk exceeds file bounds.' }
            $kind = [Text.Encoding]::ASCII.GetString($bytes, $offset + 4, 4)
            if ($kind -eq 'IHDR') {
                if ($length -ne 13) { throw 'Invalid PNG header size.' }
                $width = Read-BigEndian $bytes ($offset + 8); $height = Read-BigEndian $bytes ($offset + 12)
                if ($width -lt 1 -or $height -lt 1 -or $width * [long]$height -gt 2097152 -or
                    $bytes[$offset + 16] -ne 8 -or $bytes[$offset + 17] -ne 6 -or $bytes[$offset + 20] -ne 0) {
                    throw 'Expected bounded noninterlaced 8-bit RGBA PNG.'
                }
            }
            elseif ($kind -eq 'IDAT') { $compressed.Write($bytes, $offset + 8, $length) }
            elseif ($kind -eq 'IEND') { $ended = $true; break }
            $offset += 12 + $length
        }
        if (-not $ended -or $width -eq 0) { throw 'Incomplete snapshot PNG.' }
        $compressed.Position = 0
        $zlib = [IO.Compression.ZLibStream]::new($compressed, [IO.Compression.CompressionMode]::Decompress, $true)
        $stride = $width * 4; $raw = [byte[]]::new(($stride + 1) * $height)
        try {
            $read = 0
            while ($read -lt $raw.Length) {
                $count = $zlib.Read($raw, $read, $raw.Length - $read)
                if ($count -eq 0) { throw 'Truncated snapshot pixel data.' }; $read += $count
            }
            if ($zlib.ReadByte() -ne -1) { throw 'Unexpected trailing decompressed pixel data.' }
        }
        finally { $zlib.Dispose() }
        $pixels = [byte[]]::new($stride * $height)
        for ($row = 0; $row -lt $height; $row++) {
            if ($raw[$row * ($stride + 1)] -ne 0) { throw 'Snapshot encoder changed PNG row filters; update this bounded decoder.' }
            [Array]::Copy($raw, $row * ($stride + 1) + 1, $pixels, $row * $stride, $stride)
        }
        return @{ width = $width; height = $height; rgbaSha256 = Get-BytesHash $pixels; pixels = $pixels }
    }
    finally { $compressed.Dispose() }
}
function Count-PixelColor([byte[]]$Pixels, [int[]]$Rgb) {
    $matches = 0
    for ($index = 0; $index -lt $Pixels.Length; $index += 4) {
        if ([Math]::Abs([int]$Pixels[$index] - $Rgb[0]) -le 1 -and
            [Math]::Abs([int]$Pixels[$index + 1] - $Rgb[1]) -le 1 -and
            [Math]::Abs([int]$Pixels[$index + 2] - $Rgb[2]) -le 1 -and $Pixels[$index + 3] -eq 255) { $matches++ }
    }
    return $matches
}
function New-SnapshotRequest($Inspection, [string]$Mode = 'diagnostic', [string]$Lighting = 'game', [string]$Archive = '', [string]$ArchiveHash = '') {
    $request = [ordered]@{ schemaVersion = 1; inputSha256 = $Inspection.inputSha256; sourceRevision = $Inspection.sourceRevision
        position = @(0, -3, 4); target = @(0, 0, 0); fieldOfViewDegrees = 65; width = 256; height = 192
        nearPlane = 0.01; farPlane = 100; mode = $Mode }
    if ($Mode -eq 'lit') { $request.lightingMode = $Lighting; $request.resourceArchives = @(@{ path = $Archive; sha256 = $ArchiveHash }) }
    if ($Mode -eq 'lit' -and $Lighting -eq 'mono') { $request.renderProfile = 'palette' }
    return $request
}
function Invoke-Snapshot([string]$Name, [string]$LevelPath, $Request) {
    $requestText = Convert-Request $Request
    $path = Join-Path $scratch "$Name.png"
    $result = Invoke-Agent $Name @('snapshot', $LevelPath, '-', $path) $requestText
    Confirm-Check "$Name reports the output hash and byte count" ((Get-Hash $path) -eq $result.outputSha256 -and (Get-Item -LiteralPath $path).Length -eq $result.outputBytes)
    Confirm-Check "$Name binds source, revision and exact request" ($result.inputSha256 -eq $Request.inputSha256 -and $result.sourceRevision -eq $Request.sourceRevision -and $result.requestSha256 -eq (Get-BytesHash $utf8.GetBytes($requestText)))
    Confirm-Check "$Name uses an offscreen explicit camera" (-not $result.guiLaunched -and $result.camera.up -eq 'Z' -and $result.cameraSha256 -match '^[0-9a-f]{64}$' -and
        ($result.camera.position -join ',') -eq ($Request.position -join ',') -and ($result.camera.target -join ',') -eq ($Request.target -join ',') -and
        $result.camera.fieldOfViewDegrees -eq $Request.fieldOfViewDegrees -and $result.camera.nearPlane -eq $Request.nearPlane -and $result.camera.farPlane -eq $Request.farPlane)
    $image = Read-SnapshotPng $path
    Confirm-Check "$Name PNG dimensions and independently decoded pixels match" ($image.width -eq $Request.width -and $image.height -eq $Request.height -and $image.rgbaSha256 -eq $result.rgbaSha256)
    Confirm-Check "$Name contains visible geometry" ($result.nonBackgroundPixels -gt 100)
    $receipt.outputs.Add([ordered]@{ name = $Name; path = $path; sha256 = $result.outputSha256; rgbaSha256 = $result.rgbaSha256
        width = $image.width; height = $image.height; counts = $result.counts; warnings = $result.warnings })
    return @{ result = $result; image = $image; path = $path }
}

