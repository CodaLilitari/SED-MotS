        surfaceMono = $surfaceMonoPixels; architecturalMono = $modelMonoPixels }
    Confirm-Check 'world surface RGB traverses the real MAT/CMP/Vulkan path' ($surfaceRgbPixels -gt 100)
    Confirm-Check 'architectural RGB traverses 3DO instancing and Vulkan' ($modelRgbPixels -gt 20)
    Confirm-Check 'surface and architectural mono use their CMP ramp entries' ($surfaceMonoPixels -gt 100 -and $modelMonoPixels -gt 20)
    $base = Invoke-Snapshot 'lit-unbound-model' $unboundPath (New-SnapshotRequest $unbound 'lit' 'rgb' $archivePath $archiveHash)
    Confirm-Check 'removing ARCH binding exposes model base light' ((Count-PixelColor $base.image.pixels @(10, 8, 5)) -gt 20 -and $base.result.rgbaSha256 -ne $rgb.result.rgbaSha256)
    Confirm-Check 'removing ARCH binding preserves world surface light' ((Count-PixelColor $base.image.pixels @(30, 104, 25)) -eq $surfaceRgbPixels)

    # The result contract and asset-specific assertions below are checked against
    # the same request schema and resource loader used by the built agent.
    foreach ($render in @($rgb, $mono, $game, $base)) {
        Confirm-Check 'complete synthetic assets have no render warnings' (@($render.result.warnings).Count -eq 0)
        Confirm-Check 'lit snapshot includes world and model geometry' ($render.result.mode -eq 'lit' -and $render.result.counts.triangles -eq 4 -and
            $render.result.counts.renderedSurfaces -eq 1 -and $render.result.counts.omittedThings -eq 0 -and $render.result.counts.omittedPortalSurfaces -eq 0)
        Confirm-Check 'lit snapshot reports the exact supplied archive' ($render.result.resourceArchives.Count -eq 1 -and
            $render.result.resourceArchives[0].path -eq $archivePath -and $render.result.resourceArchives[0].sha256 -eq $archiveHash -and
            $render.result.resourceArchives[0].bytes -eq (Get-Item -LiteralPath $archivePath).Length)
        Confirm-Check 'lit snapshot resolves all three typed assets' ($render.result.usedResources.Count -eq 3)
        foreach ($resource in $render.result.usedResources) {
            $entry = @($receipt.archiveEntries | Where-Object { $_.name.Replace('\', '/') -eq $resource.entry.Replace('\', '/') })
            Confirm-Check 'used resource bytes match their synthetic archive entry' ($entry.Count -eq 1 -and $resource.archive -eq $archivePath -and
                $resource.sha256 -eq $entry[0].sha256 -and $resource.bytes -eq $entry[0].bytes)
        }
    }
    Confirm-Check 'resolved lighting modes are explicitly reported' ($rgb.result.lightingMode -eq 'rgb' -and $game.result.lightingMode -eq 'rgb' -and $mono.result.lightingMode -eq 'mono')

    $existingHash = Get-Hash $rgb.path
    $null = Invoke-Agent 'refuse-png-overwrite' @('snapshot', $levelPath, '-', $rgb.path) (Convert-Request $rgbRequest) 4
    Confirm-Check 'existing PNG bytes survive overwrite refusal' ((Get-Hash $rgb.path) -eq $existingHash)
    $staleRequest = New-SnapshotRequest $inspection 'lit' 'rgb' $archivePath ('0' * 64)
    $stalePath = Join-Path $scratch 'must-not-write-stale.png'
    $stale = Invoke-Agent 'refuse-stale-archive' @('snapshot', $levelPath, '-', $stalePath) (Convert-Request $staleRequest) 4
    Confirm-Check 'stale archive is refused before creating output' (-not (Test-Path -LiteralPath $stalePath) -and (Convert-Request $stale) -match '(?i)archive.*changed')
    $strictRequest = New-SnapshotRequest $inspection 'lit' 'rgb' $missingPath $missingHash
    $strictPath = Join-Path $scratch 'must-not-write-missing.png'
    $strict = Invoke-Agent 'refuse-missing-asset-default-strict' @('snapshot', $levelPath, '-', $strictPath) (Convert-Request $strictRequest) 2
    Confirm-Check 'strict asset failure names the synthetic missing MAT' (-not (Test-Path -LiteralPath $strictPath) -and (Convert-Request $strict) -match 'agent_lit\.mat')
    foreach ($badModel in @('empty', 'huge-count', 'truncated')) {
        $invalidEntries = [ordered]@{}
        foreach ($entry in $entries.GetEnumerator()) { $invalidEntries.Add($entry.Key, $entry.Value) }
        $badText = switch ($badModel) {
            'empty' { '# no model data' }
            'huge-count' { $modelText.Replace('VERTICES 4', 'VERTICES 2147483647') }
            'truncated' { $modelText.Substring(0, $modelText.IndexOf('VERTICES 4') + 'VERTICES 4'.Length) }
        }
        $invalidEntries['3do\agent_lit.3do'] = $utf8.GetBytes($badText)
        $badArchive = Join-Path $scratch "bad-model-$badModel.gob"
        Write-NewBytes $badArchive (New-SyntheticGob $invalidEntries)
        $receipt.fixtures.Add(@{path=$badArchive;sha256=Get-Hash $badArchive;bytes=(Get-Item -LiteralPath $badArchive).Length})
        $badRequest = New-SnapshotRequest $inspection 'lit' 'rgb' $badArchive (Get-Hash $badArchive)
        $badOutput = Join-Path $scratch "must-not-write-$badModel.png"
        $badResult = Invoke-Agent "refuse-model-$badModel" @('snapshot', $levelPath, '-', $badOutput) (Convert-Request $badRequest) 2
        Confirm-Check 'malformed named model is refused before rendering or unbounded allocation' (-not (Test-Path -LiteralPath $badOutput) -and (Convert-Request $badResult) -match 'agent_lit\.3do')
    }
    $strictRequest.strictAssets = $false
    $permissive = Invoke-Snapshot 'lit-missing-asset-permissive' $levelPath $strictRequest
    Confirm-Check 'permissive render reports missing-asset warnings' (@($permissive.result.warnings).Count -gt 0 -and (Convert-Request $permissive.result.warnings) -match 'agent_lit\.mat')
    Confirm-Check 'permissive provenance identifies only the two available assets' ($permissive.result.usedResources.Count -eq 2 -and
        $permissive.result.resourceArchives[0].sha256 -eq $missingHash -and @($permissive.result.usedResources | Where-Object requested -EQ 'agent_lit.mat').Count -eq 0)

    $diagnosticRequest = New-SnapshotRequest $inspection
    $diagnosticRequest.Remove('mode') # Existing request shape keeps its default behavior.
    $diagnostic = Invoke-Snapshot 'diagnostic-default' $levelPath $diagnosticRequest
    $diagnosticChanged = Invoke-Snapshot 'diagnostic-recolored' $recoloredPath (New-SnapshotRequest $recolored)
    Confirm-Check 'diagnostic pixels remain independent of authored lighting' ($diagnostic.result.rgbaSha256 -eq $diagnosticChanged.result.rgbaSha256)
    Confirm-Check 'diagnostic still omits things and reports flat geometry' ($diagnostic.result.counts.omittedThings -eq 1 -and $diagnostic.result.renderer -match '(?i)diagnostic')
    Confirm-Check 'diagnostic does not consume resources or a lit mode' ($diagnostic.result.resourceArchives.Count -eq 0 -and
        $diagnostic.result.usedResources.Count -eq 0 -and $null -eq $diagnostic.result.lightingMode -and $diagnostic.result.counts.triangles -eq 2)
    Invoke-ResourceWorkflow $levelText $modelText $entries
    foreach ($fixture in $receipt.fixtures) { Confirm-Check 'input fixture remains byte-identical' ((Get-Hash $fixture.path) -eq $fixture.sha256) }
    $receipt.status = 'passed'
}
catch {
    $receipt.status = 'failed'; $receipt.failure = $_.Exception.GetBaseException().Message
    throw
}
finally {
    $receipt.finishedUtc = [DateTime]::UtcNow.ToString('o')
    $receipt.assertions = $receipt.checks.Count; $receipt.agentCalls = $receipt.steps.Count
    [IO.File]::WriteAllText((Join-Path $scratch 'receipt.json'), (ConvertTo-Json -InputObject $receipt -Depth 100), $utf8)
}
Write-Output "PASS: $($receipt.assertions) assertions, $($receipt.agentCalls) agent calls. Receipt: $(Join-Path $scratch 'receipt.json')"
